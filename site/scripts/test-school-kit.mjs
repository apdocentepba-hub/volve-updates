import assert from "node:assert/strict";
import {readFileSync,statSync} from "node:fs";
import {join} from "node:path";

const root="site";
const page=readFileSync(join(root,"src/routes/escuelas.tsx"),"utf8");
const landing=readFileSync(join(root,"src/routes/educacion.tsx"),"utf8");
const footer=readFileSync(join(root,"src/components/SiteFooter.tsx"),"utf8");
const fallback=readFileSync(join(root,"scripts/route-fallback.mjs"),"utf8");
const pdf=readFileSync(join(root,"public/kit-escolar-volve.pdf"));
assert.equal(pdf.subarray(0,5).toString(),"%PDF-");
assert.ok(statSync(join(root,"public/kit-escolar-volve.pdf")).size>10000,"PDF demasiado pequeño");
assert.ok(statSync(join(root,"public/kit-escolar-volve.pdf")).size<900000,"PDF demasiado grande");
assert.ok(page.includes('createFileRoute("/escuelas")'));
assert.ok(page.includes('const file = "/kit-escolar-volve.pdf"'));
assert.ok(page.includes("Descargar kit PDF para imprimir"));
assert.ok(page.includes("0")&&page.includes("15 minutos"));
assert.ok(page.includes('href={siteConfig.help.phoneHref}'),"El 0800 debe venir de la configuración oficial");
assert.ok(page.includes("https://www.unicef.org/argentina/informes/guia-apuestas-online"));
assert.ok(page.includes("https://www.unicef.org/argentina/informes/guia-docentes-educacion-financiera"));
assert.ok(page.includes("https://www.argentina.gob.ar/capital-humano/familia"));
assert.ok(page.includes("no representa ni tiene convenio"),"No atribuir patrocinio oficial");
assert.ok(page.includes("no pidas que estudiantes") || page.includes("no pidas que estudiantes".replace("no","No")),"Safety guidance present");
assert.ok(page.includes("No contiene publicidad de apuestas")||page.includes("No contiene publicidad de apuestas".toLowerCase())||page.includes("No contiene publicidad"),"School-safe content");
assert.ok(landing.includes('to="/escuelas"'),"Link from Educación");
assert.ok(footer.includes('to="/escuelas"'),"Link from footer");
assert.ok(fallback.includes('"escuelas":'),"Render direct path fallback");
assert.ok(readFileSync(join(root,"dist/escuelas/index.html"),"utf8").includes('property="og:title"'));
assert.ok(readFileSync(join(root,"dist/escuelas/index.html"),"utf8").includes("Kit educativo para escuelas y familias"));
