//go:build windows

package main

// Offline publisher handoff, READ ONLY: neither signs a grant nor changes
// the installed motor, Task Scheduler, DNS, registry or recovery files.
import (
 "context"
 "crypto/ed25519"
 "crypto/sha256"
 "encoding/base64"
 "encoding/hex"
 "encoding/json"
 "errors"
 "fmt"
 "os"
 "path/filepath"
 "time"

 "volve-browser-protection/motorupdate"
)

type installedUnsignedMigrationDraftOutput struct {
 Schema int `json:"schema"`
 Component string `json:"component"`
 Draft motorupdate.UnsignedLegacyMigrationDraft `json:"draft"`
 ExactUnsignedPermitBase64 string `json:"exact_unsigned_permit_base64"`
 NoInstallPermission bool `json:"no_install_permission"`
 Notice string `json:"notice"`
}

// The native probes are re-executed both while preparing the publisher
// review and AGAIN while preparing its exact-signing draft. This prevents a
// signed candidate or task XML from being silently replaced between the two.
func buildInstalledUnsignedMigrationDraftReadOnly(
 ctx context.Context,root,candidate,panelVersion string,
 pub ed25519.PublicKey,elevated bool,
 probes livePublisherReviewProbes,issuedAt time.Time,
)(installedUnsignedMigrationDraftOutput,error) {
 var zero installedUnsignedMigrationDraftOutput
 packet,err:=buildInstalledPublisherReviewReadOnly(ctx,root,candidate,panelVersion,pub,elevated,probes)
 if err!=nil{return zero,fmt.Errorf("publisher identity not proven: %w",err)}
 oldExe:=filepath.Join(root,dnsServiceFile)
 backupDir:=filepath.Join(root,localRecoveryFolder,localRecoverySnapshot)
 if packet.FromTaskXMLSHA256==""||packet.FromSHA256==""{
  return zero,errors.New("old SYSTEM task and motor hashes absent")
 }
 preflight:=func()error{
  if err:=ctx.Err();err!=nil{return err}
  if _,err:=probes.Preflight();err!=nil{return fmt.Errorf("SYSTEM/DNS preflight changed: %w",err)}
  xml,err:=probes.TaskXML(ctx,oldExe)
  if err!=nil{return fmt.Errorf("live old task no longer observable: %w",err)}
  if len(xml)==0||len(xml)>1<<20{return errors.New("live task XML missing or too large")}
  hash:=sha256.Sum256(xml)
  if hex.EncodeToString(hash[:])!=packet.FromTaskXMLSHA256{
   return errors.New("live SYSTEM task XML changed after publisher review")
  }
  if err:=probes.RunningMotor(ctx,oldExe,packet.FromSHA256);err!=nil{
   return fmt.Errorf("running original DNS motor changed after publisher review: %w",err)
  }
  return nil
 }
 draft,err:=motorupdate.PrepareLegacyMigrationDraftReadOnly(
  ctx,oldExe,backupDir,candidate,panelVersion,pub,
  probes.ProtectBackup,preflight,issuedAt,
 )
 if err!=nil{return zero,fmt.Errorf("offline signing draft refused: %w",err)}
 if draft.Review!=packet||draft.SignaturePresent||draft.MigrationAuthorized||draft.ReadyToSwitch{
  return zero,errors.New("publisher review changed or an unsigned draft claimed installation permission")
 }
 exact,err:=motorupdate.DraftPermitBytesReadOnly(draft)
 if err!=nil{return zero,fmt.Errorf("canonical unsigned permit bytes invalid: %w",err)}
 sum:=sha256.Sum256(exact)
 if hex.EncodeToString(sum[:])!=draft.PermitJSONSHA256{
  return zero,errors.New("offline signing payload hash mismatch")
 }
 if err:=ctx.Err();err!=nil{return zero,err}
 return installedUnsignedMigrationDraftOutput{
  Schema:1,Component:"dns-engine-offline-publisher-draft-only",
  Draft:draft,ExactUnsignedPermitBase64:base64.StdEncoding.EncodeToString(exact),
  NoInstallPermission:true,
  Notice:"READ ONLY, unsigned publisher review. Do not use as a signed permit or execute a motor migration. The exact Base64 bytes are for independent OFFLINE editorial review/signing only.",
 },nil
}

// An explicit administrator CLI, never called from the normal Update button.
// The publisher private key is NOT loaded or generated by this process.
// The output contains an unsigned permit and a byte-for-byte Base64 copy,
// printed only to the invoking administrator; it is not uploaded or saved.
func runInstalledUnsignedMigrationDraftCLI(candidate string)error{
 if !isAdmin(){return errors.New("Administrator required; no change was made")}
 if !filepath.IsAbs(candidate)||filepath.Clean(candidate)!=candidate{
  return errors.New("candidate must be an absolute clean path; no change was made")
 }
 key,err:=base64.StdEncoding.Strict().DecodeString(updaterPublicKey)
 if err!=nil||len(key)!=ed25519.PublicKeySize{
  return errors.New("pinned public key unavailable; no change was made")
 }
 root,err:=installRoot();if err!=nil{return fmt.Errorf("installed root unavailable: %w",err)}
 ctx,cancel:=context.WithTimeout(context.Background(),75*time.Second)
 defer cancel()
 report,err:=buildInstalledUnsignedMigrationDraftReadOnly(ctx,root,candidate,version,
  ed25519.PublicKey(key),true,livePublisherReviewProbes{
   Preflight:preflightMotorUpgradeReadOnly,
   TaskXML:readPublisherReviewLiveTaskXML,
   RunningMotor:verifyResidentRunningMotorReadOnly,
   ProtectBackup:checkSealedLegacyRecoveryACL,
  },time.Now().UTC())
 if err!=nil{return err}
 raw,err:=json.MarshalIndent(report,"","  ")
 if err!=nil{return err}
 _,err=fmt.Fprintln(os.Stdout,string(raw))
 return err
}
